// ============================================================================
// menu_item.dart — รูปข้อมูลของเมนูหนึ่งรายการ
//
// ไฟล์นี้อยู่ในชั้น model ของแอป ไม่มีโค้ดที่เกี่ยวกับหน้าจอและไม่มีโค้ดที่ติดต่อ
// ฐานข้อมูล หน้าที่ของไฟล์นี้คือกำหนดว่า "เมนูหนึ่งรายการประกอบด้วยอะไรบ้าง"
//
// ── ส่วนที่ให้มาแล้ว (ไม่ต้องแก้) ────────────────────────────────────────────
//   - ฟิลด์ id · name · price · imagePath
//   - MenuItem.fromMap()  สร้างเมนูหนึ่งรายการจากข้อมูลที่อ่านมาเป็นรูป Map
//
// ไฟล์นี้ไม่มีจุดที่ต้องเติม
// ============================================================================

class MenuItem {
  const MenuItem({
    required this.id,
    required this.name,
    required this.price,
    required this.imagePath,
  });

  /// รหัสของเมนูรายการนี้ ใช้แยกว่าเป็นคนละรายการกัน
  final String id;

  /// ชื่อที่แสดงบนจอ
  final String name;

  /// ราคาเป็นบาท เก็บเป็นจำนวนเต็มเพราะร้านคิดราคาเป็นบาทถ้วน
  final int price;

  /// เส้นทางของภาพในโฟลเดอร์ assets เช่น assets/images/pad-thai.jpg
  /// ค่าว่างได้ — การ์ดเมนูจะแสดงกรอบแทนภาพให้เอง
  final String imagePath;

  /// สร้างเมนูหนึ่งรายการจากข้อมูลที่อ่านมาเป็นรูป Map
  ///
  /// เมื่อคุณทำงานข้อ ① เสร็จ ข้อมูลที่อ่านจาก Cloud Firestore จะมาถึงฟังก์ชันนี้
  /// ในรูป Map เช่นเดียวกัน จึงเรียกใช้ฟังก์ชันนี้ได้โดยไม่ต้องเขียนใหม่
  /// ชื่อฟิลด์ที่อ่านตรงนี้ต้องตรงกับชื่อฟิลด์ที่คุณสร้างไว้ในฐานข้อมูล
  factory MenuItem.fromMap(String id, Map<String, dynamic> data) {
    return MenuItem(
      id: id,
      name: (data['name'] as String?) ?? '',
      price: (data['price'] as num?)?.toInt() ?? 0,
      imagePath: (data['imagePath'] as String?) ?? '',
    );
  }
}
