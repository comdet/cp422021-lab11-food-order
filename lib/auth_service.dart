  //   เข้าสู่ระบบต่อทันที
  //   ผลที่ต้องได้: บัญชีที่สมัครจากในแอปปรากฏในหน้า Authentication ของคอนโซล
  //   พร้อมรหัสประจำตัวผู้ใช้ (uid) หนึ่งค่า
  //
  // ถ้าสมัครไม่สำเร็จ ให้โยนข้อผิดพลาดออกไปตามเดิม จอเข้าสู่ระบบจับไปแสดงเอง
