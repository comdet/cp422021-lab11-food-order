  // ต้องทำ: พาบัญชีที่สมัครไว้แล้วเข้าสู่ระบบด้วยอีเมลและรหัสผ่านที่ผู้ใช้กรอก
  //   ถ้าเข้าสู่ระบบไม่สำเร็จ ให้โยนข้อผิดพลาดออกไปตามเดิม
  Future<void> signInWithEmail(String email, String password) async {
    throw UnimplementedError('ยังไม่ได้ทำ — งานข้อ ④ ของแล็บ');
  }

