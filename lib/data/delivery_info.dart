class DeliveryInfo {
  const DeliveryInfo({
    required this.label,
    required this.address,
    required this.fee,
  });

  /// ชื่อเรียกสั้น ๆ ของที่อยู่ เช่น หอพัก หรือ บ้าน
  final String label;

  /// ที่อยู่ปลายทางที่จะเอาอาหารไปส่ง
  final String address;

  /// ค่าส่งเป็นบาท
  final int fee;

  static const DeliveryInfo demo = DeliveryInfo(
    label: 'หอพัก',
    address: 'หอพักนักศึกษา ม.ขอนแก่น อ.เมือง จ.ขอนแก่น',
    fee: 15,
  );
}
